<h2>Where Toy Testing Is Done</h2>
<p>For the BIS licence, samples are tested in:</p>
<ul>
<li><strong>The factory's in-house lab,</strong> for the routine tests listed in the BIS product manual</li>
<li><strong>BIS labs or BIS-recognised labs in India,</strong> for the samples BIS draws during inspection and surveillance</li>
</ul>
<p>Foreign test reports, including EN 71 or ASTM F963 reports, are useful for design checks, but <strong>BIS does not accept them in place of testing to the Indian Standard</strong>.</p>

<h2>Samples: How Many to Plan For</h2>
<p>Sample needs depend on the toy and on which parts apply. Destructive tests such as drop, tension and flammability use up samples, and heavy metal and phthalate tests need material from each colour and component. Ask the lab for the exact count per model before shipping, and keep extra samples ready in case of a retest.</p>
<p>After the licence, BIS keeps testing. Surveillance for toys includes <strong>one factory sample and two market samples each year</strong>, tested in BIS or BIS-recognised labs.</p>

<h2>Cost and Timeline</h2>
<p>Lab charges depend on:</p>
<ul>
<li>How many IS 9873 parts apply, and whether IS 15644 is needed</li>
<li>The number of colours and materials, since chemical tests are done per material</li>
<li>Whether models can be grouped under one test</li>
</ul>
<p>Get a written quote per model from the lab. For time, a full IS 9873 set usually takes <strong>two to four weeks</strong> once samples reach the lab. Chemical and electric toy tests can take longer, and any failure adds a retest.</p>

<h2>Common Reasons Toys Fail</h2>
<ul>
<li><strong>Small parts</strong> that detach in torque or tension tests on toys for children under 3</li>
<li><strong>Heavy metals in paint or coatings,</strong> often from a cheaper paint supplier</li>
<li><strong>Phthalates in soft PVC</strong> parts such as squeeze toys and doll bodies</li>
<li><strong>Flammability of fabric</strong> and hair on soft toys and costumes</li>
<li><strong>Battery compartments</strong> that open without a tool in electric toys</li>
</ul>
<p>Most failures trace back to material changes. Lock down paint, plastic and fabric suppliers before you test, and tell the factory not to change them without approval.</p>

