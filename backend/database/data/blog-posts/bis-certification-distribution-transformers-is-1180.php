<h2>BEE Star Labelling</h2>
<p>Distribution transformers are under BEE's mandatory star labelling programme. The star rating depends on total losses at 50% and 100% load. BEE has notified a <strong>revised loss table from 1 January 2027</strong>, so ratings designed to the old table may lose stars. Plan redesigns and retests before that date. See our <a href="/certification/india/bee-certification-services">BEE certification services</a>.</p>

<h2>Cost and Timeline</h2>
