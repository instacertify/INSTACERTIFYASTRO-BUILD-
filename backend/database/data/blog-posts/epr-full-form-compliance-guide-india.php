<li><strong>Penalties under the Environment (Protection) Act, 1986,</strong> which after the 2023 amendments are monetary penalties.</li>
<li><strong>Suspension or cancellation of registration,</strong> which stops you placing products on the market.</li>
<li><strong>Problems with marketplaces and buyers,</strong> who increasingly ask for EPR registration numbers.</li>
</ul>
