<h2>Who Must Apply for CRS Registration?</h2>
<p>The registration is always issued in the name of the <strong>actual manufacturing factory</strong>, not the trader or importer. This matters for:</p>
<ul>
<li><strong>Indian manufacturers</strong> who apply directly.</li>
<li><strong>Brand owners</strong> who outsource production. The factory is registered and the brand is linked to it, often through a brand-owner affidavit.</li>
<li><strong>Importers</strong>, who cannot hold the registration themselves. The overseas factory must be registered, and each brand it makes for India must be covered.</li>
<li><strong>Foreign manufacturers</strong>, who must appoint an <strong>Authorised Indian Representative (AIR)</strong> with an Indian address. The AIR signs the application and is legally answerable in India.</li>
</ul>

<h2>BIS CRS Registration Process: Step by Step</h2>

<h3>1. Confirm the product, standard and edition</h3>
<p>Identify the exact product category, the notified Indian Standard and the edition currently in force. Standards are revised often. Testing to an old edition is one of the most common reasons a report is rejected.</p>

<h3>2. Create a login on the CRS portal</h3>
<p>Applications are filed on the BIS CRS portal (crsbis.in). The factory creates a login by uploading its business licence in English, showing the factory name, address and manufacturing activity. Our <a href="/resources/blogs/crsbis-portal-guide-login-application-r-number">crsbis.in portal guide</a> walks through each screen.</p>

<h3>3. Generate a test request and send samples</h3>
<p>From the portal, you generate a test request and pick a BIS-recognised lab that has the standard in its scope. The sample and test request must reach the lab within <strong>60 days</strong> of generating the request.</p>

<h3>4. Lab testing and report verification</h3>
<p>The lab tests the sample and issues the report through the portal. You verify the report. The application must be filed within <strong>90 days</strong> of the report date, otherwise the report expires and the product has to be tested again.</p>

<h3>5. File the application</h3>
<p>The application is filed on Form I with the test report reference, the declaration of conformity and the supporting documents. Fees are paid online.</p>

<h3>6. BIS review and grant</h3>
<p>BIS checks the report, the documents and the declarations. Any shortfall is raised as a query on the portal. Once satisfied, BIS grants the registration and issues the R-number.</p>

<h3>7. Mark the product</h3>
<p>Print the Standard Mark with the R-number and IS number as required by the marking guidelines for your product. The label, packaging, manual and BIS application must all show the same brand and model details.</p>

