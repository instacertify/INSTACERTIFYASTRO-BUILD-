<h2>Validity, Renewal and Annual Fees</h2>
<p>Under the 2026 amendment, a CRS registration can be granted for <strong>up to five years</strong> and renewed for further periods of up to five years. The longer validity does not remove the yearly duty: the <strong>annual fee and production details must be sent in advance every year</strong>. If they are late, the registration can be suspended until the dues and a late fee are paid.</p>

<h2>Common Mistakes That Delay CRS Registration</h2>
<ul>
<li><strong>Testing to an old edition of the standard.</strong> Always check the edition in force on the day you send samples.</li>
<li><strong>Letting the test report expire.</strong> The 90-day window passes quickly if documents are not ready.</li>
<li><strong>Mismatched details.</strong> The factory name, address, brand and model must match exactly across the report, label and application.</li>
<li><strong>Applying in the importer's name.</strong> Only the manufacturing factory can be registered.</li>
<li><strong>Assuming one model covers all.</strong> Series grouping has rules. A model with a different PCB, rating or critical component may need its own test.</li>
<li><strong>Relying on CE, UL or CB reports.</strong> BIS accepts only reports from BIS-recognised labs against the Indian Standard.</li>
</ul>

