<p>If you make or import electronics for the Indian market, there is a good chance your product falls under the <strong>BIS Compulsory Registration Scheme (CRS)</strong>. Mobile chargers, laptops, LED lamps, power banks, CCTV cameras, lithium batteries and solar inverters are only a few examples.</p>
<p>The short answer: a product covered by CRS must be <strong>tested in a BIS-recognised lab in India</strong>, <strong>registered with BIS</strong> and <strong>marked with the Standard Mark and its R-number</strong> before it is sold, imported or listed online. Customs and marketplaces check for it.</p>
<p>This guide explains how the scheme works in 2026, how to tell if your product is covered, what the process looks like, what BIS charges and the mistakes that cause most delays.</p>

<h2>What Is the BIS Compulsory Registration Scheme?</h2>
<p>CRS is run by the <strong>Bureau of Indian Standards (BIS)</strong> under <strong>Scheme-II of Schedule-II of the BIS (Conformity Assessment) Regulations, 2018</strong>. The products it covers are notified by the Ministry of Electronics and Information Technology (MeitY) and, for some products, the Ministry of New and Renewable Energy (MNRE).</p>
<p>It works on <strong>self-declaration backed by third-party testing</strong>:</p>
<ul>
<li>A BIS-recognised lab tests a sample of your model against the notified Indian Standard.</li>
<li>You apply to BIS with that test report and a declaration of conformity.</li>
<li>BIS reviews the file and grants a registration with a unique number, called the R-number.</li>
<li>You print the Standard Mark with the R-number on the product, packaging and manual.</li>
</ul>
<p>Unlike the ISI mark, <strong>there is no BIS factory inspection before registration</strong>. BIS can still pick up market samples later for surveillance testing.</p>

<h2>Which Products Are Covered by CRS in 2026?</h2>
<p>The list has grown in phases since 2013 and now runs to well over 70 product categories. Typical groups include:</p>
