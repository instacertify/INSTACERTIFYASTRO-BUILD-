<p>If you are setting up a factory, a hospital, a hotel or almost any business that discharges effluent or emissions, you will need a <strong>CTO certificate</strong> before you start operations.</p>
<p><strong>CTO stands for Consent to Operate.</strong> It is the permission issued by the <strong>State Pollution Control Board</strong> under the <strong>Water (Prevention and Control of Pollution) Act, 1974</strong> and the <strong>Air (Prevention and Control of Pollution) Act, 1981</strong>. It confirms your unit has the pollution controls the board requires. In Uttar Pradesh, CTO is issued by the <strong>Uttar Pradesh Pollution Control Board (UPPCB)</strong>.</p>

<h2>CTE vs CTO</h2>
<table>
<thead><tr><th></th><th>CTE (Consent to Establish)</th><th>CTO (Consent to Operate)</th></tr></thead>
