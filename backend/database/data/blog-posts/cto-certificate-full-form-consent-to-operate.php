<tr><td>When</td><td>Before construction or expansion</td><td>Before starting production, after the unit is built</td></tr>
<tr><td>What the board checks</td><td>Site, process, proposed pollution controls</td><td>Installed effluent treatment, air pollution controls, compliance with CTE conditions</td></tr>
<tr><td>Validity</td><td>Until the unit is set up, within the time allowed</td><td>Set by category and state practice (see below)</td></tr>
</tbody>
