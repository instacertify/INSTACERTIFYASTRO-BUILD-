<p>You cannot skip CTE and go straight to CTO for a new unit. Expansion or change in product mix also needs fresh consent.</p>

<h2>Who Needs a CTO?</h2>
<p>Industries are grouped by pollution potential:</p>
<ul>
<li><strong>Red:</strong> highly polluting, such as chemicals, pharmaceuticals, tanneries and large thermal plants</li>
<li><strong>Orange:</strong> moderately polluting, such as many engineering and food processing units</li>
<li><strong>Green:</strong> low polluting, such as some assembly and packaging units</li>
<li><strong>White:</strong> practically non-polluting. <strong>Exempt from consent</strong>, but must inform the board</li>
</ul>
<p>Hospitals, hotels, large buildings and commercial establishments may also need consent depending on their size and discharges.</p>

<h2>CTO Validity</h2>
<p>UPPCB has historically granted CTO for fixed periods by category:</p>
