<ol>
<li><strong>Product review:</strong> we confirm the inverter type, the standards, the series plan and the samples needed.</li>
<li><strong>Series planning:</strong> the highest-rated model is tested for safety and islanding to cover the series, while efficiency is tested for each model. Good planning keeps testing costs down.</li>
<li><strong>Sample submission:</strong> 3 samples for on-grid and hybrid, 2 for off-grid, sent to a BIS-recognised lab with the technical documents.</li>
