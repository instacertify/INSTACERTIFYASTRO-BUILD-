<h2>Common Worries, Answered</h2>
<h3>"Will one failed test cost me everything again?"</h3>
<p>No. If a sample fails, only the failed part is usually repeated after you fix the design. A design review before testing is the best way to avoid failures, and we do it as standard.</p>
<h3>"Do I need a separate licence for every rating?"</h3>
<p>Not necessarily. With a well-planned series, one licence can cover several ratings. Only the efficiency tests are per model.</p>
<h3>"I import inverters. Who holds the licence?"</h3>
<p>The licence is held by the <strong>manufacturer</strong>, for its factory. Foreign factories need an Authorised Indian Representative and pay the ₹27,000 government fee. Importers should check the registration covers the exact models and factory before shipping.</p>
<h3>"Can I sell while my application is pending?"</h3>
<p>No. Inverters can be sold only after the registration is granted and the product carries the BIS Standard Mark with its registration number.</p>
<h3>"My inverter is a normal home inverter, not solar. Is it simpler?"</h3>
<p>Yes. A single standard (IS 16242 Part 1:2025), about 2 weeks of testing from ₹40,000 to ₹45,000 and no additional report fee. The government fee is the same.</p>

