<li><strong>Part 15 Subpart B:</strong> unintentional radiators, such as digital devices, computers, displays and LED drivers</li>
<li><strong>Part 15 Subpart C:</strong> intentional radiators, such as Bluetooth and 2.4 GHz devices</li>
<li><strong>Part 15 Subpart E:</strong> 5 GHz Wi-Fi devices</li>
