<p>Any electronic product sold in the United States must meet <strong>FCC rules</strong> on radio frequency emissions. For Indian manufacturers and brands exporting to the US, or selling through Amazon US, FCC approval is often the first compliance question.</p>
<p><strong>In short:</strong> products that do not intentionally transmit radio signals usually follow <strong>SDoC (Supplier's Declaration of Conformity)</strong>, which is testing plus a self-declaration. Products with radios such as Bluetooth, Wi-Fi, LTE or RFID need <strong>FCC certification</strong>: testing in an FCC-recognised lab, a grant from a <strong>Telecommunication Certification Body (TCB)</strong> and an <strong>FCC ID</strong> on the label. Testing can be done in India.</p>

