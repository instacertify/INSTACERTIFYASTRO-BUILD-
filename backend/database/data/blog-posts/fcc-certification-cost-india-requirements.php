<h2>FCC Certification Requirements</h2>
<ol>
<li><strong>Grantee code:</strong> register with the FCC to get an FRN and a grantee code. This is the first part of every FCC ID you will use.</li>
<li><strong>US agent:</strong> designate an agent in the US for service of process.</li>
<li><strong>Testing:</strong> RF tests for each radio (output power, bandwidth, spurious emissions, frequency stability), plus Part 15B emissions.</li>
<li><strong>RF exposure:</strong> SAR testing for devices used close to the body, or an MPE evaluation for others.</li>
<li><strong>Documents:</strong> block diagram, schematics, operational description, internal and external photos, user manual with FCC statements, label and label location.</li>
<li><strong>TCB review and grant.</strong> The TCB reviews the file and issues the grant, which then appears in the FCC database.</li>
</ol>
