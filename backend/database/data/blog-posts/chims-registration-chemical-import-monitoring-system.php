<h3>3. MSIHC Rules for hazardous chemicals</h3>
<p>If your chemical is listed in the schedules to the <strong>MSIHC Rules, 1989</strong>, the importer must give the authorities advance information about the import, provide safety data, keep records and follow labelling and storage rules. A complete <strong>safety data sheet (SDS or MSDS)</strong> is essential.</p>

<h3>4. CIB and RC registration</h3>
<p>Insecticides, pesticides and their technical grade materials need registration with the <strong>Central Insecticides Board and Registration Committee</strong> before import.</p>

