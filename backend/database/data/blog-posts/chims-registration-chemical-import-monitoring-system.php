<p>Many importers search for "CHIMS registration" thinking it is a chemical import licence. It is not. <strong>CHIMS stood for Chip Imports Monitoring System</strong>, a DGFT registration for imports of <strong>semiconductor chips</strong>, and it was <strong>discontinued in November 2024</strong>.</p>
<p>There is no separate "Chemical Import Monitoring System" in India. If you import chemicals, what you need depends on the chemical: an <strong>IEC</strong>, possibly a <strong>BIS licence</strong>, <strong>hazardous chemical compliance</strong> under the MSIHC Rules and, for some products, registrations such as <strong>CIB and RC</strong>. This guide explains each.</p>

