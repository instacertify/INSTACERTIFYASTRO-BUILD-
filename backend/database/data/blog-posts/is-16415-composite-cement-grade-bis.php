<h2>Common Mistakes</h2>
<ul>
<li><strong>Working to the original 2015 values.</strong> The amended standard has different composition ranges and much higher strength.</li>
<li><strong>Marketing a "grade".</strong> IS 16415 has no grade designation, so do not label composite cement as 43 or 53 grade.</li>
<li><strong>Weak raw material control.</strong> Fly ash and slag quality vary by source and need regular testing.</li>
</ul>

