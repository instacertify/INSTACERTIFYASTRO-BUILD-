<h2>Is the BIS Licence Mandatory?</h2>
<p>Yes. Cement types including composite cement are covered by the <strong>Cement Quality Control Order</strong>. No one may make, import, sell or store composite cement for sale without a valid BIS licence and the ISI mark. Our article on <a href="/resources/blogs/is-your-cement-legal-why-the-bis-isi-mark-is-non-negotiable-in-2026">why the ISI mark is non-negotiable for cement</a> covers enforcement in more detail.</p>

<h2>How Manufacturers Get the BIS Licence for IS 16415</h2>
<ol>
<li><strong>Set up the lab.</strong> The plant needs the in-house testing listed in the BIS product manual, including compressive strength, fineness, setting time, soundness and chemical analysis.</li>
<li><strong>Prepare records.</strong> Raw material checks, mix proportions, calibration and test records.</li>
<li><strong>Apply on Manak Online</strong> with documents and fees.</li>
<li><strong>Factory inspection.</strong> A BIS officer checks the plant and lab and draws samples.</li>
<li><strong>Independent testing</strong> of samples in a BIS or BIS-recognised lab.</li>
<li><strong>Grant of licence</strong> with a CM/L number once results conform and fees are paid.</li>
</ol>
<p>Foreign cement plants follow the same steps under <a href="/resources/blogs/bis-fmcs-certification-foreign-manufacturers">FMCS</a>.</p>

