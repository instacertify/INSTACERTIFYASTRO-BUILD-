<h2>Question 4: Do You Have a Certificate of Analysis?</h2>
<p>Where required, we ask for a <strong>certificate of analysis (CoA)</strong> for the product or batch you are shipping. A CoA gives <strong>measured values</strong> for your actual product, such as:</p>
