<h2>Key Requirements</h2>

<h3>1. ESD control programme plan</h3>
<p>A written plan covering scope, roles, required ESD items, test methods and limits. It should match how your factory actually works.</p>

<h3>2. Training plan</h3>
<p>Initial training for everyone who handles ESD-sensitive items, before they handle them, and recurrent training at set intervals. Keep records for each person.</p>

<h3>3. Compliance verification plan</h3>
<p>How often each ESD control item is checked and against which limits: wrist straps, footwear, work surfaces, floors, ionisers, seating and carts.</p>

<h3>4. Grounding and bonding</h3>
<p>A grounding system that connects all conductors, including people, to a common ground point.</p>

<h3>5. Personnel grounding</h3>
<p>Wrist straps for seated work and footwear with ESD flooring for standing or moving work, with daily checks at entry.</p>

<h3>6. ESD Protected Areas</h3>
<p>Marked areas with access control, grounded surfaces and control of insulators. Ionisers are used where insulators cannot be removed.</p>

<h3>7. Packaging and marking</h3>
<p>Packaging that protects items when they leave the EPA, as defined in your packaging plan and customer contracts, and correct ESD marking on packages.</p>

