<p>Electrostatic discharge damages electronic components every day, often without any visible sign. A part that is weakened by ESD may pass final test and fail in the field. That is why many global customers now ask their suppliers for <strong>ANSI/ESD S20.20 certification</strong>.</p>
<p><strong>In short:</strong> ANSI/ESD S20.20 is the standard for an <strong>ESD control programme</strong>. To get certified, you write an ESD control plan, set up <strong>ESD Protected Areas (EPAs)</strong>, train staff, verify equipment regularly and pass an audit by a certification body recognised under the ESD Association's programme.</p>

<h2>What ANSI/ESD S20.20 Covers</h2>
<p>The standard has two kinds of requirements:</p>
<ul>
<li><strong>Administrative:</strong> ESD control programme plan, training plan, product qualification and compliance verification plan</li>
<li><strong>Technical:</strong> grounding and bonding, personnel grounding, EPA requirements, packaging and marking</li>
