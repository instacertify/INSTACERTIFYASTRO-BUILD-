<tr><td>Industrial</td><td>Batteries for industrial use, inverters, UPS, solar storage and telecom</td></tr>
<tr><td>Electric vehicle</td><td>Traction batteries for EVs, including two- and three-wheelers</td></tr>
</tbody>
</table>
<p>Each category has its own targets, so classify each battery correctly.</p>

<h2>Targets Under BWMR</h2>
<ul>
<li><strong>Collection or recycling targets</strong> for producers, based on the quantity of batteries placed on the market in earlier years, rising over time.</li>
<li><strong>Material recovery targets</strong> for recyclers. From 2026-27 these are 90% for portable and EV batteries and 60% for automotive and industrial batteries.</li>
