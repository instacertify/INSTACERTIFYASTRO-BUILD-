<p>The <strong>Battery Waste Management Rules, 2022 (BWMR)</strong> made every company that puts batteries on the Indian market responsible for collecting and recycling them. If you make, import or sell batteries, or products with batteries inside, you need <strong>battery EPR registration</strong> on the CPCB portal before you place them on the market.</p>
<p>This guide explains who is covered, the battery categories, targets, fees and the registration process.</p>

<h2>Who Is a Producer Under BWMR?</h2>
<p>A producer is anyone who manufactures, sells under its own brand or imports:</p>
<ul>
<li>Batteries on their own</li>
<li>Equipment containing batteries, such as phones, laptops, UPS systems and power tools</li>
<li>Vehicles containing batteries, including EVs</li>
</ul>
<p>So an importer of Bluetooth speakers is a battery producer as well as an e-waste producer.</p>

