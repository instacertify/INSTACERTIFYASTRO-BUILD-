<p>Once the report is issued and verified on the portal, the application is filed on Form I with the declaration of conformity and documents. The application must be filed within <strong>90 days of the report date</strong>.</p>

<h2>Stage 6: BIS Review and Grant (2 to 4 Weeks)</h2>
<p>BIS checks the test report, documents, declarations and label. If something is missing or does not match, a query is raised on the portal and the clock effectively stops until you answer. A clean file with consistent details moves fastest.</p>

