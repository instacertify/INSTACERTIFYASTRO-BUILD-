<h2>Who Can Apply?</h2>
<p>The licence is issued to the <strong>manufacturing factory</strong>. Importers, trading companies and brand owners cannot hold it. If you buy from a factory, that factory must apply. The licence then covers the brands and varieties named in it.</p>

<h2>The Role of the Authorised Indian Representative</h2>
<p>Every FMCS applicant must nominate an <strong>AIR</strong>, a person or company resident in India who:</p>
