<p>If your factory is outside India and your product is covered by a BIS Quality Control Order, you cannot ship it to India until the factory holds a BIS licence. For ISI mark products, the route is the <strong>Foreign Manufacturers Certification Scheme (FMCS)</strong>.</p>
<p><strong>In short:</strong> under FMCS the overseas factory appoints an <strong>Authorised Indian Representative (AIR)</strong>, applies to BIS, hosts a <strong>BIS inspection at the factory</strong>, has samples <strong>tested in India</strong>, gives a <strong>USD 10,000 bank guarantee</strong> and then marks its products with the ISI mark and its CM/L licence number. BIS indicates about <strong>six months</strong> on average from a complete application.</p>

<h2>What Is FMCS and Which Products Does It Cover?</h2>
<p>FMCS is the overseas version of the ISI mark scheme (Scheme-I of the BIS Conformity Assessment Regulations, 2018). It applies to products such as:</p>
<ul>
<li>Steel and stainless steel products</li>
<li>Industrial chemicals and polymers</li>
<li>Household electrical appliances under the IS 302 series</li>
<li>Electrical accessories, cables and switchgear</li>
<li>Toys under IS 9873 and IS 15644</li>
