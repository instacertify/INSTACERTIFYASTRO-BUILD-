<p>Choose the AIR carefully. BIS can hold the AIR responsible if marked products are found to fail.</p>

<h2>FMCS Process: Step by Step</h2>

<h3>1. Confirm the standard and the factory's readiness</h3>
<p>Identify the Indian Standard, the varieties you want covered and the in-house tests the BIS product manual expects. The factory must be able to test to the Indian Standard, not only to ISO, EN or ASTM.</p>

<h3>2. Prepare the application and technical file</h3>
<p>The application includes factory details, contact person and AIR, management details, raw materials, production and process flow chart, factory layout, test equipment list and quality control plan, with undertakings. Documents in other languages need certified English translations.</p>

<h3>3. Submit and pay the application fee</h3>
<p>BIS records the application once it is complete and the fee is paid. Missing documents are the most common reason for an early pause.</p>

<h3>4. Factory inspection</h3>
<p>BIS officers visit the factory. They check production, raw material control, in-house testing and records, see tests performed, and draw samples. The applicant pays the inspection charges and the officers' travel, visa, insurance and per diem.</p>

<h3>5. Sample testing in India</h3>
<p>The samples are sent by the applicant to a BIS lab or BIS-recognised lab in India and tested against the Indian Standard. <strong>Foreign test reports are not accepted in place of this testing.</strong></p>

<h3>6. Grant of licence</h3>
<p>If the inspection and test results are satisfactory and fees are paid, BIS grants the licence and the CM/L number. The manufacturer signs an agreement and indemnity bond and gives a <strong>USD 10,000 performance bank guarantee</strong> from a bank with a branch in India.</p>

<h3>7. Marking and surveillance</h3>
<p>Products must carry the ISI mark, the IS number and the CM/L licence number. BIS keeps checking through surveillance inspections and factory and market samples.</p>

