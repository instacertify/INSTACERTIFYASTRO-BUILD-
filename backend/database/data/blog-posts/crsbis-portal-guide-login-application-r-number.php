<p>Every BIS CRS registration starts and ends on one website: <strong>crsbis.in</strong>, the official portal of the Bureau of Indian Standards for the Compulsory Registration Scheme. It is where you get a login, raise test requests, file the application, answer BIS queries, pay fees and renew.</p>
<p>The portal is functional but not always intuitive, and small mistakes there cause real delays. This guide walks through each task in the order you will meet it.</p>
<p>If you are not yet sure whether your product needs CRS, read our guide to the <a href="/resources/blogs/bis-compulsory-registration-scheme-crs-explained">BIS Compulsory Registration Scheme</a> first.</p>

<h2>Who Should Use the Portal?</h2>
<p>The login belongs to the <strong>manufacturing factory</strong>, because the registration is issued to the factory. That includes:</p>
<ul>
<li>Indian factories applying for their own products.</li>
<li>Overseas factories, working through their <strong>Authorised Indian Representative (AIR)</strong>.</li>
<li>Factories that make products for other brands, which register the factory and link each brand.</li>
</ul>
<p>Importers and traders do not get their own registration. They usually help the factory gather documents and follow up.</p>

<h2>Step 1: Get a Login</h2>
<p>On the portal's registration page, the factory signs up by uploading its <strong>business licence in English</strong>. It must show the factory name, the address and that the factory carries out manufacturing. A licence in another language needs a certified English translation.</p>
<p>Fill in the contact person, email and mobile number carefully. All portal messages, queries and OTPs go there, and changing them later carries a fee.</p>
<p><strong>Common errors:</strong> a trading licence instead of a manufacturing licence, an address that differs from the one on the test report, or a scanned document that is hard to read.</p>

<h2>Step 2: Generate a Test Request</h2>
<p>After logging in, you create a test request for each product or series:</p>
<ol>
<li>Enter the sample details: product, standard, brand, models and ratings.</li>
<li>Choose a BIS-recognised lab from the list that has your standard in its scope.</li>
<li>Wait for the lab to accept the request.</li>
<li>Print the test request with its QR code and attach it to the sample packet.</li>
</ol>
<p>The sample and the test request must reach the lab <strong>within 60 days</strong> of generating the request.</p>
<p><strong>Tip:</strong> choose the lab by scope, current edition of the standard and queue, not only price.</p>

<h2>Step 3: Verify the Test Report</h2>
<p>The lab uploads the report to the portal against your test request. Check every line before you accept it:</p>
<ul>
<li>Factory name and address exactly as on your login</li>
<li>Brand and model numbers</li>
<li>Ratings and the edition of the standard</li>
<li>Any models listed as covered by the series</li>
</ul>
<p>Ask the lab to correct errors before you file. Fixing them later is slower.</p>

<h2>Step 4: File the Application</h2>
<p>Applications are filed on <strong>Form I</strong>. You enter the test request reference, which pulls the report into the application, then add the declaration of conformity and supporting documents and pay the fees online. File within <strong>90 days of the report date</strong>, or the report expires.</p>
<p>Typical uploads include the trademark certificate or brand authorisation, affidavits, the AIR nomination for foreign factories, the label artwork and the user manual. Our <a href="/resources/blogs/bis-crs-registration-time-timeline">CRS timeline guide</a> shows how long each stage usually takes.</p>

<h2>Step 5: Answer Queries</h2>
<p>If BIS needs more information, a query appears in your login and an email is sent to the registered contact. Reply on the portal with the requested documents. A query left unanswered holds the whole application, so check the login every day while an application is open.</p>

<h2>Step 6: Download the Registration and Mark the Product</h2>
<p>When BIS grants the registration, the certificate and <strong>R-number</strong> are available in your login. Print the Standard Mark with the R-number and IS number on the product, packaging and manual as required for your product.</p>

<h2>How to Check an R-Number</h2>
<p>Buyers, marketplaces and customs often want to confirm a registration. The portal has a public <strong>Registered Manufacturers search</strong>:</p>
<ol>
<li>Open the search from the registration page of crsbis.in.</li>
<li>Search by R-number, manufacturer, brand or product category.</li>
<li>Check that the status is active and that the manufacturer, brand and model match the product.</li>
</ol>
<p>A real R-number on the wrong brand or model is still non-compliant. The registration only covers what is listed in it.</p>

<h2>Adding Models, Brands or Changes</h2>
<p>To add a new model, test it first and then file an inclusion request with the new report. Changes to the factory name, address, management, AIR or contact details are separate requests, each with its own fee. Keep the registration details up to date so they always match your labels.</p>

<h2>Renewal and Annual Fees</h2>
<p>Under the BIS (Conformity Assessment) Amendment Regulations, 2026, CRS registrations can run for <strong>up to five years</strong>. The <strong>annual fee and production details must still be paid and filed in advance every year</strong>. If they are late, the registration can be suspended until the dues and late fee are paid. Before expiry, file the renewal request with the renewal fee from your login.</p>

