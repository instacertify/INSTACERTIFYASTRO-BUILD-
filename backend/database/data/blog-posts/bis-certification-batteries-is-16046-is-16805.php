<h2>Cost and Timeline</h2>
<p>BIS fees for CRS registration are the application fee, the annual licence fee and the processing fee, with concessions for micro, small and medium enterprises. Lab charges depend on the standard, the number of models and whether cells and packs are tested together. Ask the lab for a quote per model before you ship.</p>
