</ul>
<p>Some tests need cells conditioned through charge and discharge cycles first, which is why battery testing takes longer than many other CRS products.</p>

<h3>Cell vs pack registration</h3>
<p>BIS treats the cell and the battery pack as separate products. The cell inside a pack should hold its own registration, and the pack is registered on top of that. If your cell supplier is not registered, start there. Many delays come from packs that cannot be registered because the cell is not.</p>

<h2>IS 16805: Industrial and Stationary Lithium Batteries</h2>
<p>IS 16805 is aligned with <strong>IEC 62619</strong> and covers safety of secondary lithium cells and batteries for industrial use, including stationary storage and backup power. It covers tests such as short circuit, impact, drop, thermal abuse, overcharge, forced discharge and internal short circuit, and it checks the battery management system's protective functions.</p>
<p>If your battery is for an inverter, UPS, solar storage or telecom site, IS 16046 is usually the wrong standard. Our <a href="/resources/blogs/bis-certification-inverters-ups-2026">guide to BIS for UPS and inverters</a> explains how the battery and the equipment fit together.</p>

<h2>IS 15549: Stationary VRLA Lead-Acid Batteries</h2>
<p>IS 15549 specifies stationary valve-regulated lead-acid batteries, the type used in large UPS systems, telecom and power plants. Tests cover capacity, endurance, charge retention, gas emission and other performance checks. Buyers such as utilities and telecom operators often ask for IS 15549 test reports in tenders.</p>

<h2>BIS CRS Registration Process for Batteries</h2>
<ol>
<li><strong>Confirm the standard and the model list.</strong> Group models into a series where BIS guidelines allow, to reduce testing.</li>
<li><strong>Register the cell first,</strong> if you make packs.</li>
<li><strong>Send samples to a BIS-recognised lab</strong> through the CRS portal. Get the test request generated before shipping samples.</li>
<li><strong>Review the test report.</strong> Check model numbers, ratings and photos match your label and documents.</li>
<li><strong>File the application</strong> on the CRS portal with the report, documents and fees. Foreign manufacturers need an Authorised Indian Representative.</li>
