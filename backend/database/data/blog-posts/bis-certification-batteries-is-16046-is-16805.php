<h2>IS 16046: The Standard for Portable Batteries</h2>
<p>IS 16046 sets safety requirements for portable sealed secondary cells and batteries made from them. It is the standard behind most battery CRS registrations. Typical tests include:</p>
<ul>
<li>Continuous charging at low rate</li>
<li>Vibration and moulded case stress at high temperature</li>
<li>External short circuit</li>
<li>Free fall</li>
<li>Thermal abuse</li>
<li>Crush</li>
