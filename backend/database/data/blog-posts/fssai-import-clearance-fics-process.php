<h2>How Food Import Clearance Works</h2>
<ol>
<li><strong>Bill of entry filed</strong> on ICEGATE through the customs single window. FSSAI receives the import details automatically.</li>
<li><strong>Risk assessment:</strong> FSSAI's risk management system decides whether the consignment is cleared on documents, visually inspected or sampled.</li>
<li><strong>Document scrutiny</strong> by the FSSAI Authorised Officer: licence, invoice, packing list, certificate of origin and health certificate where needed.</li>
<li><strong>Visual inspection</strong> of the goods and labels.</li>
