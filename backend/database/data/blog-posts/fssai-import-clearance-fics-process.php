<h2>How Long Does Clearance Take?</h2>
<p>Consignments cleared on documents move fastest. Those selected for sampling take longer because of lab testing, often several days or more depending on the tests. Complete documents and correct labels are the best way to avoid delays and demurrage.</p>

<h2>Common Mistakes</h2>
