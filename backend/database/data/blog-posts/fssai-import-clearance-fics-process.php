<h2>Shelf Life Rule</h2>
<p>At the time of import, food must have at least <strong>60% of its original shelf life or three months</strong> left, whichever is less. Plan shipping times so products do not arrive too close to expiry.</p>

<h2>If a Sample Fails</h2>
<ul>
<li>FSSAI issues an <strong>NCR</strong>, and the goods cannot be sold in India.</li>
