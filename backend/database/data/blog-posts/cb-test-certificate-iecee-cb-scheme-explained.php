<p>The IECEE is the IEC System of Conformity Assessment Schemes for Electrotechnical Equipment and Components. Its CB Scheme is a multilateral agreement between certification bodies in member countries. The idea is simple: a test done by one member's lab can be accepted by another member's certification body.</p>
