<p>Under the mark you will see a licence number in the format <strong>CM/L-XXXXXXXXXX</strong>. That number links the product to one factory and one licence.</p>

<h2>A Short History: From ISI to BIS</h2>
<ul>
<li><strong>1947:</strong> The Indian Standards Institution is set up to write national standards.</li>
