<p><strong>ISI stands for Indian Standards Institution.</strong> It was India's national standards body, set up in 1947. In 1987 it became the <strong>Bureau of Indian Standards (BIS)</strong>, but the certification mark kept the original name. Today the ISI mark shows that BIS has licensed a factory to mark a product because it conforms to the relevant Indian Standard.</p>

<h2>What Does the ISI Mark Mean?</h2>
<p>The ISI mark is BIS's <strong>product certification mark under Scheme-I</strong> of the BIS (Conformity Assessment) Regulations, 2018. A product carrying it should have:</p>
<ul>
<li>Been made in a factory that holds a valid BIS licence for that product</li>
<li>Been tested against a specific Indian Standard, shown as an IS number near the mark</li>
